    override fun readGlyph32(codePoint: Int, bold: Boolean): ByteArray = scaleGlyph(readGlyph8(codePoint), 4, 4)

    override fun readGlyph16(codePoint: Int, bold: Boolean): ByteArray = scaleGlyph(readGlyph8(codePoint), 2, 2)

    override fun readGlyph12(codePoint: Int, bold: Boolean): ByteArray = scaleGlyph(readGlyph8(codePoint), 2, 2).copyOf(24)

    override fun readGlyph8(codePoint: Int): ByteArray {
        val ch = codePoint.toChar().uppercaseChar()
        val rows = glyphRows[ch] ?: glyphRows['?']!!
        val out = ByteArray(8)
        for (x in 0 until 8) {
            var col = 0
            for (y in 0 until 8) {
                if (((rows[y].toInt() ushr (7 - x)) and 1) != 0) {
                    col = col or (1 shl y)
                }
            }
            out[x] = col.toByte()
        }
        return out
    }

    private fun scaleGlyph(source8: ByteArray, scaleX: Int, scaleY: Int): ByteArray {
        val width = 8 * scaleX
        val height = 8 * scaleY
        val bytesPerColumn = (height + 7) / 8
        val out = ByteArray(width * bytesPerColumn)
        for (sx in 0 until 8) {
            val sourceColumn = source8[sx].toInt() and 0xFF
            for (xRepeat in 0 until scaleX) {
                val dx = sx * scaleX + xRepeat
                for (sy in 0 until 8) {
                    if (((sourceColumn ushr sy) and 1) == 0) continue
                    for (yRepeat in 0 until scaleY) {
                        val dy = sy * scaleY + yRepeat
                        val index = dx * bytesPerColumn + (dy / 8)
                        out[index] = (out[index].toInt() or (1 shl (dy % 8))).toByte()
                    }
                }
            }
        }
        return out
    }

